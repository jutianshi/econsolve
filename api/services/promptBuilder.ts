/**
 * Prompt构建器
 * 用于构建三阶段流水线的AI提示词
 */

/**
 * 构建题目理解阶段的Prompt
 * @param problemText 题目文本
 */
export function buildAnalysisPrompt(problemText: string): string {
  return `你是一位资深的经济学考研辅导专家，擅长分析各类经济学题目。请对以下经济学考研题目进行深入分析。

## 待分析的题目
${problemText}

## 分析要求
请从以下几个方面对题目进行全面分析：

### 1. 题目类型识别
判断本题属于哪种类型：
- **计算题**：需要通过数学计算得出具体数值或表达式
- **证明题**：需要运用经济理论进行逻辑推导和证明
- **分析题**：需要对经济现象或理论进行分析阐述

### 2. 学科领域识别
确定题目所属的经济学分支：
- 微观经济学（消费者理论、生产者理论、市场结构等）
- 宏观经济学（国民收入、通货膨胀、经济增长等）
- 计量经济学（回归分析、假设检验等）
- 其他（制度经济学、发展经济学等）

### 3. 核心知识点提取
列出解决此题必须掌握的核心知识点，包括：
- 相关的经济学术语和概念
- 涉及的经济学定理或定律
- 需要运用的数学工具

### 4. 难度评估
根据以下标准评估题目难度：
- 简单：直接套用公式即可求解
- 中等：需要多步推导或综合多个知识点
- 困难：涉及复杂模型或需要创新性思维

### 5. 解题思路概述
简要说明解题的整体思路和方法论

### 6. 涉及公式
列出解题过程中可能用到的所有数学公式

请以JSON格式返回分析结果，包含以下字段：
{
  "problemType": "calculation|proof|analysis",
  "subject": "学科领域",
  "keyPoints": ["知识点1", "知识点2", ...],
  "difficulty": "easy|medium|hard",
  "approach": "解题思路概述",
  "formulas": ["公式1", "公式2", ...]
}`
}

/**
 * 构建推理解答阶段的Prompt
 * @param analysis 第一阶段的分析结果
 */
export function buildSolutionPrompt(analysis: string): string {
  return `你是一位经验丰富的经济学考研导师，擅长为学生提供清晰、详细的解题过程。

## 题目分析结果
${analysis}

## 解答要求
基于上述分析结果，请提供完整的、详细的解答过程：

### 1. 分步骤解答
将解答过程分解为清晰的步骤，每个步骤应包含：
- 步骤标题：简明扼要地概括本步骤内容
- 详细内容：完整的推理和计算过程
- 关键公式：本步骤使用的重要公式（如有）

### 2. 最终答案
给出明确的最终答案，确保答案的完整性和准确性

### 3. 方法总结
总结本题使用的核心方法和技巧，帮助举一反三

### 4. 易错点提示
指出学生在解此类题目时容易犯的错误：
- 常见的概念混淆
- 容易忽略的条件
- 计算中的易错点
- 逻辑推理中的陷阱

请以JSON格式返回解答结果，格式如下：
{
  "steps": [
    {
      "stepNumber": 1,
      "title": "步骤标题",
      "content": "详细内容",
      "formula": "可选的LaTeX公式"
    }
  ],
  "finalAnswer": "最终答案",
  "methodSummary": "方法总结",
  "commonMistakes": ["易错点1", "易错点2", ...]
}

注意：
- 解答过程要详尽，便于学生理解每个环节
- 数学推导要严谨，逻辑链条要完整
- 使用规范的经济学符号和术语`
}

/**
 * 构建LaTeX生成阶段的Prompt
 * @param problem 原始题目
 * @param solution 第二阶段的解答结果
 * @param template 用户选择的模板内容
 */
export function buildLatexPrompt(problem: string, solution: string, template: string): string {
  return `你是一位精通LaTeX排版的学术文档专家，专门负责将经济学考研题目的解答转换为高质量的LaTeX代码。

## 原始题目
${problem}

## 解答内容
${solution}

## LaTeX模板
\`\`\`latex
${template}
\`\`\`

## 生成要求
请按照以下要求生成完整的LaTeX文档：

### 1. 文档结构
- 严格遵循提供的模板结构
- 保持模板中的 preamble 设置不变
- 在正文区域填入题目和解答内容

### 2. 排版规范
- 使用专业的数学环境（equation, align, cases 等）
- 公式编号清晰，引用正确
- 文字与公式的间距适当
- 使用中文时加载 ctex 宏包

### 3. 内容组织
- **题目部分**：使用 problem 或 question 环境
- **分析部分**：简要呈现题目分析要点
- **解答部分**：分步骤展示完整解答过程
- **答案部分**：突出显示最终结果

### 4. 数学表达
- 所有数学符号使用数学模式
- 分式使用 \\frac{}{}
- 上下标使用 _ 和 ^
- 希腊字母使用标准命令
- 多行公式使用 align 环境

### 5. 质量要求
- 代码可编译，无语法错误
- 格式美观，符合学术规范
- 注释清晰，便于维护修改

请直接返回完整的可编译LaTeX代码，不要添加额外的解释文字。`
}

/**
 * 构建合并版超级Prompt（一次性完成所有阶段）
 * @param problem 题目文本
 * @param template 模板内容
 */
export function buildUnifiedPrompt(problem: string, template: string): string {
  return `你是一位全能的经济学考研AI助教，集成了题目分析、解答生成和LaTeX排版三大能力。请对以下题目进行完整的解析。

## 待解析的题目
${problem}

## LaTeX排版模板
\`\`\`latex
${template}
\`\`\`

## 任务要求（三阶段流水线）

### 📋 第一阶段：深度题目分析
对题目进行全面剖析：
1. **题型识别**：判断是计算题、证明题还是分析题
2. **学科定位**：确定所属经济学分支（微观/宏观/计量等）
3. **知识图谱**：提取所有相关知识点和理论工具
4. **难度评级**：评估为简单/中等/困难
5. **策略制定**：规划最优解题路径
6. **公式清单**：列出所需的所有数学公式

### ✍️ 第二阶段：专业解答生成
提供完整的解题方案：
1. **步骤拆解**：将复杂问题分解为清晰的子步骤
2. **严密推导**：每一步都有充分的逻辑依据
3. **精确计算**：数值计算准确无误
4. **方法提炼**：总结可迁移的解题方法论
5. **避坑指南**：标注常见错误和注意事项

### 📐 第三阶段：高质量LaTeX输出
生成可直接编译的专业文档：
1. **结构完整**：遵循模板框架，文档结构清晰
2. **排版精美**：数学公式规范，版面整洁美观
3. **语法正确**：确保LaTeX代码无编译错误
4. **学术规范**：符合经济学论文的排版标准

## 输出格式要求
请以JSON格式返回完整结果：
{
  "analysis": {
    "problemType": "calculation|proof|analysis",
    "subject": "学科领域",
    "keyPoints": ["知识点列表"],
    "difficulty": "easy|medium|hard",
    "approach": "解题思路",
    "formulas": ["公式列表"]
  },
  "solution": {
    "steps": [
      {
        "stepNumber": 1,
        "title": "步骤标题",
        "content": "详细内容",
        "formula": "LaTeX公式"
      }
    ],
    "finalAnswer": "最终答案",
    "methodSummary": "方法总结",
    "commonMistakes": ["易错点列表"]
  },
  "latexCode": {
    "code": "完整可编译的LaTeX源码",
    "templateName": "使用的模板名称",
    "qualityScore": 95
  }
}

## 质量标准
- ✅ 分析准确全面，不遗漏关键信息
- ✅ 解答逻辑严密，步骤清晰易懂
- ✅ LaTeX代码规范，可直接使用XeLaTeX编译
- ✅ 内容真实可信，符合考研难度水平
- ✅ 使用中文回答，专业术语准确`
}
